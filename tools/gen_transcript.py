#!/usr/bin/env python3
"""Generate obj_test/test_transcript.cpp: per-proc golden transcripts.

Every weak lifted-proc wrapper is called in a forked child once per
input vector (zero / mid / LFSR-random / all-ones / boundary registers)
with fabricated sentinel state and a 250ms watchdog.  On return the
child reports:

    class   PASS / FALSE / TIMEOUT / CRASHn / EARLYEXITn
    regs    all guest registers + flags
    hmem    FNV-1a of the whole guest memory image (m2c::m)
    hvga    FNV-1a of the 64KB vgaRam array

so any behavioral change in any proc -- registers, flags, or memory
writes -- shows up as a diff against tests/transcript_expected.txt.

Usage: gen_transcript.py <obj-dir> <out.cpp>
"""
import re
import subprocess
import sys

CPP_KEYWORDS = {
    "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor",
    "bool", "break", "case", "catch", "char", "char8_t", "char16_t",
    "char32_t", "class", "compl", "concept", "const", "consteval",
    "constexpr", "constinit", "const_cast", "continue", "co_await",
    "co_return", "co_yield", "decltype", "default", "delete", "do",
    "double", "dynamic_cast", "else", "enum", "explicit", "export",
    "extern", "false", "float", "for", "friend", "goto", "if", "inline",
    "int", "long", "mutable", "namespace", "new", "noexcept", "not",
    "not_eq", "nullptr", "operator", "or", "or_eq", "private", "protected",
    "public", "register", "reinterpret_cast", "requires", "return",
    "short", "signed", "sizeof", "static", "static_assert", "static_cast",
    "struct", "switch", "template", "this", "thread_local", "throw",
    "true", "try", "typedef", "typeid", "typename", "union", "unsigned",
    "using", "virtual", "void", "volatile", "wchar_t", "while", "xor",
    "xor_eq",
}

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def weak_proc_names(objdir):
    out = subprocess.run(
        ["bash", "-c",
         f"find -L '{objdir}' -name '*.o' ! -name 'asm.o' | xargs nm -C"],
        capture_output=True, text=True, check=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 3 and re.fullmatch(r"[0-9a-fA-F]+", parts[0]) \
                and parts[1] == "W":
            dem = " ".join(parts[2:])
        else:
            continue
        name = dem.split("(")[0].strip()
        if name.startswith("_") or "::" in name:
            continue
        if IDENT.match(name) and name not in CPP_KEYWORDS:
            names.add(name)
    return sorted(names)


TEMPLATE_HEAD = """\
/* GENERATED by tools/gen_transcript.py - do not edit.
 * Per-proc golden transcripts: every wrapper x input vector, forked
 * child, sentinel stack, result regs + memory hashes reported via pipe.
 */
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <cstdint>
#include <unistd.h>
#include <fcntl.h>
#include <signal.h>
#include <sys/types.h>
#include <sys/wait.h>
#include <sys/time.h>
#include <map>
#include <string>
#include <vector>
#include <algorithm>

#include "asm.h"

using m2c::_STATE;

namespace m2c { extern int init(_STATE*); }

typedef bool (*proc_t)(m2c::_offsets, _STATE*);
"""

TEMPLATE_TAIL = """\
extern unsigned char vgaRam[];

static _STATE st;

/* guest memory image is 0x15c3fa bytes (m2c::m symbol size) */
static const size_t MEMSZ  = 0x15c3fa;
static const size_t VGASZ  = 64000;
static const int    PAR    = 8;      /* concurrent children */

/* input vectors: eax ebx ecx edx esi edi ebp  (ds=7, es=0x6000 always) */
static const dd VEC[5][7] = {
    {0,0,0,0,0,0,0},                                              /* V0 zero */
    {0x1000,0x0080,0x0040,0x0002,0x7000,0x7100,0x7200},           /* V1 mid */
    {0x9e37,0x1357,0x9bdf,0x0246,0xaced,0x55aa,0x3333},           /* V2 rand */
    {0xffff,0xffff,0xffff,0xffff,0xffff,0xffff,0xffff},           /* V3 ones */
    {0x7fff,0x8000,0x0001,0xffff,0x0000,0x0000,0x0000},           /* V4 bound */
};

struct Rec {
    uint32_t idx;
    uint8_t  vec;
    uint8_t  cls;          /* 0=PASS 1=FALSE */
    uint16_t flags;
    uint32_t r[9];         /* eax ebx ecx edx esi edi ebp esp eip */
    uint16_t s[6];         /* cs ds es fs gs ss */
    uint64_t hmem, hvga;
};

static void reset_state() {
    std::memset(&st, 0, sizeof st);
    st.ds = st.es = 7;
    st.ss = 0x900;
    st.esp = 0xff00;
    *(dw*)m2c::raddr_(st.ss, 0xff00)     = 0;
    *(dw*)m2c::raddr_(st.ss, 0xff00 + 2) = 0;
}

static uint64_t fnv(const void* p, size_t n) {
    const unsigned char* b = (const unsigned char*)p;
    uint64_t h = 1469598103934665603ull;
    for (size_t i = 0; i < n; ++i) { h ^= b[i]; h *= 1099511628211ull; }
    return h;
}

struct Task { int idx, vec, fd; };

int main(int argc, char** argv) {
    const char* out = argc > 1 ? argv[1] : "tests/transcript_current.txt";
    /* pin the host clock: procs reading int1Ah/time get a fixed epoch */
    setenv("M2C_DET", "1", 0);
    setenv("M2C_DET_EPOCH", "1990-06-01 12:00:00", 0);
    std::vector<std::string> lines;
    std::map<pid_t, Task> pend;
    int counts[8] = {0};
    int total = 0;

    auto spawn = [&](int i, int v) {
        int p[2];
        if (pipe(p) < 0) return;
        pid_t pid = fork();
        if (pid == 0) {
            close(p[0]);
            reset_state();
            st.eax = VEC[v][0]; st.ebx = VEC[v][1]; st.ecx = VEC[v][2];
            st.edx = VEC[v][3]; st.esi = VEC[v][4]; st.edi = VEC[v][5];
            st.ebp = VEC[v][6];
            st.es  = 0x6000;
            std::freopen("/dev/null", "w", stdout);
            std::freopen("/dev/null", "w", stderr);
            struct itimerval it = {};
            it.it_value.tv_sec = 1;
            /* procs doing real SDL/host work can take >1s legitimately */
            static const char* LONG[] = {
                "vga_vmode", "initair1", "initgnd1", "initctrldevice",
                "initexpmodel", "initflyview", "initmodel", "readdacblock",
                "recaljoysticks", "sortctrljoy1", "sortctrljoy2",
                "savemap", "overflowintr",
            };
            for (const char* s : LONG)
                if (!std::strcmp(PROCS[i].name, s)) it.it_value.tv_sec = 3;
            /* SND event procs wait on the host audio queue (~1s) */
            if (std::strstr(PROCS[i].name, "event")) it.it_value.tv_sec = 3;
            setitimer(ITIMER_REAL, &it, nullptr);
            bool r = PROCS[i].fn ? PROCS[i].fn(0, &st) : false;
            Rec rec = {};
            rec.idx = (uint32_t)i; rec.vec = (uint8_t)v;
            rec.cls = r ? 0 : 1;
            rec.flags = (st.CF?1:0)|(st.PF?2:0)|(st.AF?4:0)|(st.ZF?8:0)
                       |(st.SF?16:0)|(st.DF?32:0)|(st.OF?64:0)
                       |(st.IF?128:0)|(st.TF?256:0);
            rec.r[0]=st.eax; rec.r[1]=st.ebx; rec.r[2]=st.ecx;
            rec.r[3]=st.edx; rec.r[4]=st.esi; rec.r[5]=st.edi;
            rec.r[6]=st.ebp; rec.r[7]=st.esp; rec.r[8]=st.eip;
            rec.s[0]=st.cs; rec.s[1]=st.ds; rec.s[2]=st.es;
            rec.s[3]=st.fs; rec.s[4]=st.gs; rec.s[5]=st.ss;
            rec.hmem = fnv(&m2c::m, MEMSZ);
            rec.hvga = fnv(vgaRam, VGASZ);
            (void)!write(p[1], &rec, sizeof rec);
            _exit(r ? 0 : 10);
        }
        close(p[1]);
        pend[pid] = Task{i, v, p[0]};
    };

    auto drain = [&](pid_t pid, int status) {
        Task& t = pend[pid];
        Rec rec;
        bool got = read(t.fd, &rec, sizeof rec) == (ssize_t)sizeof rec;
        close(t.fd);
        const char* nm = PROCS[t.idx].name;
        char cls[24];
        if (got) {
            std::snprintf(cls, sizeof cls, "%s", rec.cls ? "FALSE" : "PASS");
            counts[rec.cls ? 1 : 0]++;
        } else if (WIFSIGNALED(status) && WTERMSIG(status) == SIGALRM) {
            std::snprintf(cls, sizeof cls, "TIMEOUT"); counts[2]++;
        } else if (WIFSIGNALED(status)) {
            std::snprintf(cls, sizeof cls, "CRASH%d", WTERMSIG(status));
            counts[3]++;
        } else {
            std::snprintf(cls, sizeof cls, "EARLYEXIT%d", WEXITSTATUS(status));
            counts[4]++;
        }
        char ln[256];
        if (got) {
            uint64_t hr = fnv(rec.r, sizeof rec.r) ^ fnv(rec.s, sizeof rec.s);
            std::snprintf(ln, sizeof ln,
                "V%d %-28s %-9s r=%016llx f=%04x m=%016llx v=%016llx",
                t.vec, nm, cls,
                (unsigned long long)hr, rec.flags,
                (unsigned long long)rec.hmem, (unsigned long long)rec.hvga);
        } else {
            std::snprintf(ln, sizeof ln, "V%d %-28s %s", t.vec, nm, cls);
        }
        lines.push_back(ln);
        pend.erase(pid);
        ++total;
    };

    for (unsigned i = 0; i < NPROCS; ++i)
        for (int v = 0; v < 5; ++v) {
            while ((int)pend.size() >= PAR) {
                int status = 0;
                pid_t d = waitpid(-1, &status, 0);
                if (d > 0 && pend.count(d)) drain(d, status);
            }
            spawn(i, v);
        }
    while (!pend.empty()) {
        int status = 0;
        pid_t d = waitpid(-1, &status, 0);
        if (d > 0 && pend.count(d)) drain(d, status);
    }

    std::sort(lines.begin(), lines.end());
    FILE* f = std::fopen(out, "w");
    if (!f) { std::perror(out); return 2; }
    for (auto& l : lines) std::fprintf(f, "%s\\n", l.c_str());
    std::fprintf(f, "# pass=%d false=%d timeout=%d crash=%d exit=%d total=%d\\n",
                 counts[0], counts[1], counts[2], counts[3], counts[4], total);
    std::fclose(f);
    std::printf("transcript: pass=%d false=%d timeout=%d crash=%d exit=%d total=%d\\n",
                counts[0], counts[1], counts[2], counts[3], counts[4], total);
    return 0;
}
"""


def main():
    objdir, out = sys.argv[1], sys.argv[2]
    names = weak_proc_names(objdir)
    with open(out, "w") as f:
        f.write(TEMPLATE_HEAD)
        for n in names:
            f.write(f"extern bool {n}(m2c::_offsets, _STATE*) "
                    "__attribute__((weak));\n")
        f.write("\nstruct Proc { const char* name; proc_t fn; };\n")
        f.write("static const Proc PROCS[] = {\n")
        for n in names:
            f.write(f'    {{"{n}", {n}}},\n')
        f.write("};\nstatic const unsigned NPROCS = "
                "sizeof(PROCS)/sizeof(PROCS[0]);\n")
        f.write(TEMPLATE_TAIL)
    print(f"generated {out}: {len(names)} procs")


if __name__ == "__main__":
    main()
