#!/usr/bin/env python3
"""Generate tests/test_smoke_gen.cpp: a per-proc ABI smoke test.

Enumerates every weak lifted-proc wrapper `bool name(_offsets,_STATE*)`
exported by the app objects, emits a C++ TU that calls each one in a
forked child with the fabricated sentinel state, and classifies the
outcome:

    PASS     returned true  (clean native return to C++)
    FALSE    returned false (dispatch/unwind failure mid-call)
    TIMEOUT  hung > N sec   (SIGALRM)
    CRASH    killed by another signal
    MISSING  weak symbol not linked

Results are written to tests/smoke_current.txt; tests/run_tests.sh diffs
that against tests/smoke_expected.txt so NEW failures are regressions.

Usage: gen_smoke.py <obj-dir> <out.cpp>
"""
import re
import subprocess
import sys

CPP_KEYWORDS = {
    "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor",
    "bool", "break", "case", "catch", "char", "char8_t", "char16_t",
    "char32_t", "class", "compl", "concept", "const", "consteval",
    "constexpr", "constinit", "const_cast", "continue", "co_await",
    "co_return", "co_yield", "decltype", "default", "delete", "do",
    "double", "dynamic_cast", "else", "enum", "explicit", "export",
    "extern", "false", "float", "for", "friend", "goto", "if", "inline",
    "int", "long", "mutable", "namespace", "new", "noexcept", "not",
    "not_eq", "nullptr", "operator", "or", "or_eq", "private", "protected",
    "public", "register", "reinterpret_cast", "requires", "return",
    "short", "signed", "sizeof", "static", "static_assert", "static_cast",
    "struct", "switch", "template", "this", "thread_local", "throw",
    "true", "try", "typedef", "typeid", "typename", "union", "unsigned",
    "using", "virtual", "void", "volatile", "wchar_t", "while", "xor",
    "xor_eq",
}

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def weak_proc_names(objdir):
    out = subprocess.run(
        ["bash", "-c",
         f"find -L '{objdir}' -name '*.o' ! -name 'asm.o' | xargs nm -C"],
        capture_output=True, text=True, check=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        # bsd format: <addr> W <demangled name possibly with spaces>
        if len(parts) >= 3 and re.fullmatch(r"[0-9a-fA-F]+", parts[0]) \
                and parts[1] == "W":
            dem = " ".join(parts[2:])
        else:
            continue
        name = dem.split("(")[0].strip()
        if name.startswith("_") or "::" in name:
            continue
        if IDENT.match(name) and name not in CPP_KEYWORDS:
            names.add(name)
    return sorted(names)


TEMPLATE_HEAD = """\
/* GENERATED by tools/gen_smoke.py - do not edit.
 * ABI smoke test: call every lifted proc wrapper with fabricated
 * sentinel state in a forked child; classify PASS/FALSE/TIMEOUT/CRASH.
 */
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <unistd.h>
#include <signal.h>
#include <sys/types.h>
#include <sys/wait.h>

#include "asm.h"

using m2c::_STATE;

namespace m2c { extern int init(_STATE*); }

typedef bool (*proc_t)(m2c::_offsets, _STATE*);
"""

TEMPLATE_TAIL = """\
static _STATE st;

static void reset_state() {
    std::memset(&st, 0, sizeof st);
    st.ds = st.es = 7;
    st.ss = 0x900;
    st.esp = 0xff00;
    *(dw*)m2c::raddr_(st.ss, 0xff00)     = 0;
    *(dw*)m2c::raddr_(st.ss, 0xff00 + 2) = 0;
}

/* Result collection in parent memory (no stdio FILE shared with children:
 * a proc that calls exit() would flush inherited buffers). */
static char results[260000];   /* ~32 bytes x 8k */
static unsigned rused;

static void record(const char* tag, const char* nm) {
    rused += std::snprintf(results + rused, sizeof results - rused,
                           "%s %s\\n", tag, nm);
}

int main(int argc, char** argv) {
    const char* out = argc > 1 ? argv[1] : "tests/smoke_current.txt";

    int n_pass = 0, n_false = 0, n_time = 0, n_crash = 0,
        n_miss = 0, n_exit = 0;
    for (unsigned i = 0; i < NPROCS; ++i) {
        const proc_t fn = PROCS[i].fn;
        const char* nm  = PROCS[i].name;
        if (!fn) { record("MISSING", nm); ++n_miss; continue; }

        int p[2];
        if (pipe(p) < 0) { record("PIPEFAIL", nm); continue; }
        pid_t pid = fork();
        if (pid == 0) {
            close(p[0]);
            reset_state();
            std::freopen("/dev/null", "w", stdout);
            std::freopen("/dev/null", "w", stderr);
            alarm(1);
            bool r = fn(0, &st);
            /* 'K' sentinel: distinguishes real return from a proc that
             * called exit() internally. */
            (void)!write(p[1], "K", 1);
            _exit(r ? 0 : 10);
        }
        close(p[1]);
        int status = 0;
        while (waitpid(pid, &status, 0) < 0) { /* retry on EINTR */ }
        char c = 0;
        bool returned = read(p[0], &c, 1) == 1;
        close(p[0]);
        if (!returned) {
            if (WIFSIGNALED(status) && WTERMSIG(status) == SIGALRM) {
                record("TIMEOUT", nm); ++n_time;
            } else if (WIFSIGNALED(status)) {
                char t[24];
                std::snprintf(t, sizeof t, "CRASH%d", WTERMSIG(status));
                record(t, nm); ++n_crash;
            } else {
                char t[24];
                std::snprintf(t, sizeof t, "EARLYEXIT%d", WEXITSTATUS(status));
                record(t, nm); ++n_exit;
            }
        } else if (WIFEXITED(status) && WEXITSTATUS(status) == 0) {
            ++n_pass;
        } else {
            record("FALSE", nm); ++n_false;
        }
    }

    FILE* f = std::fopen(out, "w");
    if (!f) { std::perror(out); return 2; }
    std::fwrite(results, 1, rused, f);
    std::fprintf(f, "# pass=%d false=%d timeout=%d crash=%d exit=%d "
                    "missing=%d total=%u\\n",
                 n_pass, n_false, n_time, n_crash, n_exit, n_miss, NPROCS);
    std::fclose(f);
    std::printf("smoke: pass=%d false=%d timeout=%d crash=%d exit=%d "
                "missing=%d total=%u\\n",
                n_pass, n_false, n_time, n_crash, n_exit, n_miss, NPROCS);
    return 0;
}
"""


def main():
    objdir, out = sys.argv[1], sys.argv[2]
    names = weak_proc_names(objdir)
    with open(out, "w") as f:
        f.write(TEMPLATE_HEAD)
        for n in names:
            f.write(f"extern bool {n}(m2c::_offsets, _STATE*) "
                    "__attribute__((weak));\n")
        f.write("\nstruct Proc { const char* name; proc_t fn; };\n")
        f.write("static const Proc PROCS[] = {\n")
        for n in names:
            f.write(f'    {{"{n}", {n}}},\n')
        f.write("};\nstatic const unsigned NPROCS = "
                "sizeof(PROCS)/sizeof(PROCS[0]);\n")
        f.write(TEMPLATE_TAIL)
    print(f"generated {out}: {len(names)} procs")


if __name__ == "__main__":
    main()
